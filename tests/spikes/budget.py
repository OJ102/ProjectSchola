#!/usr/bin/env python3
"""Tester's independent re-derivation of source-derived tokens in a session's MAIN context.

usage: budget.py <session.jsonl> <store> <brief.md>
Does not use dryrun.py. Walks every transcript entry (user, assistant, tool results,
attachments, system reminders), and counts text that reproduces the source: any
48-char window of a span's text or of the brief's body. Assistant output is reported
separately (paraphrase, generated by the model, not injected source).
"""
import json, re, sys
from collections import defaultdict

sess, store, brief = sys.argv[1:4]
W = 48


def n(s):
    s = s.replace('‐', '-').replace('’', "'").replace('“', '"').replace('”', '"')
    return re.sub(r'\s+', ' ', s).strip().lower()


src = [n(json.loads(l)['text']) for l in open(f"{store}/spans.jsonl")]
src.append(n(open(brief).read()))
grams = set()
for t in src:
    for i in range(0, max(1, len(t) - W + 1), 8):
        grams.add(t[i:i + W])


def strings(x):
    if isinstance(x, str):
        yield x
    elif isinstance(x, dict):
        for v in x.values():
            yield from strings(v)
    elif isinstance(x, list):
        for v in x:
            yield from strings(v)


def hits(text):
    t = n(text)
    return sum(1 for i in range(0, max(1, len(t) - W + 1)) if t[i:i + W] in grams)


tot = defaultdict(lambda: [0, 0, 0])  # role -> [entries with source, chars of those entries, matched windows]
details = []
for l in open(sess):
    if not l.strip():
        continue
    e = json.loads(l)
    if e.get('isSidechain'):
        continue  # subagent context, not main
    msg = e.get('message') or {}
    role = e.get('type')
    content = msg.get('content') if msg else None
    parts = content if isinstance(content, list) else ([{'type': 'text', 'text': content}] if isinstance(content, str) else [])
    if not parts:
        parts = [{'type': e.get('type'), 'text': ' '.join(strings({k: v for k, v in e.items() if k in ('attachment', 'content', 'toolUseResult') }))}]
    for c in parts:
        kind = c.get('type')
        if kind == 'tool_use':
            continue
        body = c.get('content') if kind == 'tool_result' else c.get('text', '')
        body = ''.join(strings(body)) if not isinstance(body, str) else body
        h = hits(body or '')
        if h:
            key = f"{role}/{kind}"
            tot[key][0] += 1
            tot[key][1] += len(body)
            tot[key][2] += h
            details.append((key, len(body), h, body[:70].replace('\n', ' ')))

main_in = sum(v[1] for k, v in tot.items() if not k.startswith('assistant/'))
print(json.dumps({'source_chars_main_input': main_in, 'tokens_est_chars_div4': main_in // 4,
                  'by_kind': {k: {'entries': v[0], 'chars': v[1], 'windows': v[2]} for k, v in tot.items()}}, indent=1))
for d in details:
    print('  ', d)

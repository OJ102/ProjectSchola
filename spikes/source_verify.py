"""Prototype citation gate (spike 0c). Deterministic: no model calls.

usage: python3 spikes/source_verify.py <storedir> <brief.md> [--allow ids-file]... [--where TEXT] [--json out.json]
       python3 spikes/source_verify.py <storedir> <brief.md> --render   (print brief with locators)

A cite is [[cite:<span-id> "<anchor>"]]. Each cite must:
  - name a span id that exists in <storedir>/spans.jsonl, inside the allowed
    set (the unit's ids file, plus prerequisites);
  - carry an anchor of >= 6 words or >= 30 chars and <= 25 words, not only
    stopwords; a span shorter than that must be quoted whole (then stopwords
    are fine: "No.");
  - match the cited span as a normalized TOKEN sequence (decision 13: word
    boundaries, so "safe" never matches inside "unsafe");
  - for noisy spans only (video cues, OCR), a fuzzy match per decisions 2 and
    16: protected tokens (negations, numbers and number words, units,
    comparatives, multiplicatives, likelihood/modal words) match exactly, a
    substitution that adds or removes a negating prefix is never noise,
    a content-word substitution is allowed only as a plural/possessive or a
    British/American spelling variant (round 5: edit distance 2 let
    cause/cure and prevent/present through),
    insertions/deletions are stopwords or fillers only, overall ratio >= 0.9,
    and more than half of the match lies in the cited cue.
Strict schema (decision 17): exact "## " headings from SCHEMA, in order, each
at most once, Core claims and Quiz seeds required. In claim sections every
non-empty line must be a schema item ("- " or "N. " for Quiz seeds) with at
least one valid cite; in other sections every line must be a "- " item.
"Where" is generated by code: one line, no cites; with --where it must equal
that text (it may name pages, since code wrote it).
Self-written locators (p. 12, pg. 12, page 12, 12:30, 1:02:03) fail anywhere
outside a cite. Exit 0 when everything passes, 1 otherwise.
"""
import difflib
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from srcnorm import display_safe, find_tokens, norm, tokens  # noqa: E402

CITE = re.compile(r'\[\[cite:([^\s\]"]+)\s+"(.*?)"\]\]')
BARE_CITE = re.compile(r"\[\[cite:[^\]]*\]\]")
SCHEMA = ["Where", "Core claims", "Definitions", "Key figures", "Equations", "Examples",
          "Prerequisites", "Quiz seeds", "Further reading", "Source caveats"]
# Every section except Where and Prerequisites carries source claims and needs
# cites (round 5: claims were smuggled into Further reading / Source caveats).
CLAIM_SECTIONS = {"Core claims", "Definitions", "Key figures", "Equations", "Examples", "Quiz seeds",
                  "Further reading", "Source caveats"}
# Prerequisites hold outside knowledge only, in a fixed, visibly non-source form
PREREQ_ITEM = re.compile(r"^- (Assumes|Earlier unit): \S")
REQUIRED = {"Core claims", "Quiz seeds"}
NOISY_KINDS = {"cue", "ocr"}
MIN_WORDS, MIN_CHARS, MAX_WORDS = 6, 30, 25
FUZZY_MIN = 0.9
STOPWORDS = set("""a an and are as at be by for from has have he her his i in is it its of on or
our she so that the their them they this to was we were what when which who will with you your
there here then than these those been being do does did not no yes but if into out up down over""".split())
FILLERS = {"um", "uh", "er", "ah", "like", "so", "okay", "ok", "you", "know", "i", "mean", "well", "right"}
NEGATIONS = {"not", "no", "never", "without", "cannot", "none", "nor", "neither", "nothing", "nobody", "nowhere"}
COMPARATIVES = {"more", "less", "fewer", "higher", "lower", "greater", "smaller", "larger", "bigger", "before",
                "after", "above", "below", "increase", "increases", "increased", "decrease", "decreases",
                "decreased", "most", "least", "better", "worse", "best", "worst", "faster", "slower", "over", "under"}
UNITS = {"%", "percent", "ms", "s", "sec", "seconds", "minutes", "hours", "days", "years", "kb", "mb", "gb", "tb",
         "k", "m", "b", "billion", "million", "thousand", "hundred", "tokens", "km", "kg", "g", "cm", "mm", "x"}
MULTIPLICATIVES = {"once", "twice", "thrice", "double", "doubled", "triple", "tripled", "half", "halved",
                   "quarter", "single", "dozen"}
MODALS = {"likely", "unlikely", "possible", "impossible", "probably", "possibly", "must", "may", "might",
          "should", "could", "can", "always", "never", "often", "rarely", "seldom", "sometimes", "usually",
          "all", "every", "some", "few", "many", "only", "certainly"}
NUMBER_WORDS = {w: str(i) for i, w in enumerate(
    "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen "
    "sixteen seventeen eighteen nineteen twenty".split())}
NUMBER_WORDS.update({w: str(10 * (i + 3)) for i, w in enumerate("thirty forty fifty sixty seventy eighty ninety".split())})
NEG_PREFIXES = ("un", "in", "im", "ir", "il", "non", "dis", "a")
SELF_LOCATOR = re.compile(r"\b(?:p|pp|pg|pgs)\.\s*\d+|\b(?:page|pages|pg)\s+\d+|\b\d{1,2}:\d{2}(?::\d{2})?\b", re.I)


def load_spans(store):
    spans = [json.loads(l) for l in open(os.path.join(store, "spans.jsonl"), encoding="utf-8")]
    return {s["id"]: s for s in spans}, [s["id"] for s in spans]


def ntoks(t):
    """Word tokens for fuzzy comparison: number words become digits, n't
    splits off, punctuation is dropped."""
    out = []
    for w in tokens(t):
        if not re.match(r"\w", w):
            continue  # punctuation would inflate the share of a window inside the cited cue
        if w.endswith("n't"):
            out += [w[:-3], "not"]
        else:
            out.append(NUMBER_WORDS.get(w, w))
    return out


def protected(t):
    return (t in NEGATIONS or t in COMPARATIVES or t in UNITS or t in MULTIPLICATIVES or t in MODALS
            or t[0].isdigit())


def negating_pair(x, y):
    for a, b in ((x, y), (y, x)):
        if any(a == p + b for p in NEG_PREFIXES) or a == b + "less":
            return True
    return False


def edit_distance(a, b):
    prev = list(range(len(b) + 1))
    for i in range(1, len(a) + 1):
        cur = [i] + [0] * len(b)
        for j in range(1, len(b) + 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] != b[j - 1]))
        prev = cur
    return prev[-1]


def _canon(w):
    """Collapse inflection and British/American spelling, nothing else."""
    for suf in ("'s", "es", "s"):
        if w.endswith(suf) and len(w) > len(suf) + 2:
            w = w[:-len(suf)]
            break
    w = re.sub(r"our\b", "or", w)
    w = re.sub(r"is(e|ed|ing|ation)$", r"iz\1", w)
    w = re.sub(r"ys(e|ed|ing)$", r"yz\1", w)
    w = re.sub(r"tre$", "ter", w)
    w = re.sub(r"ll(ed|ing|er)$", r"l\1", w)
    return w


def spelling_variant(x, y):
    """A content word may differ from the caption only as a plural/possessive
    or a British/American spelling. Any other substitution, however close
    ("cause"/"cure", "prevent"/"present", "accept"/"except"), can change the
    claim, so it is never treated as transcription noise."""
    return x == y or _canon(x) == _canon(y)


def noise_ok(a, b):
    """Is the difference between token lists a and b plausible caption noise?"""
    soft = STOPWORDS | FILLERS
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if op == "equal":
            continue
        xa, xb = a[i1:i2], b[j1:j2]
        for x, y in zip(xa, xb):
            if protected(x) or protected(y) or negating_pair(x, y) or not spelling_variant(x, y):
                return False
        if any(t not in soft or protected(t) for t in xa[len(xb):] + xb[len(xa):]):
            return False
    return True


def fuzzy(anchor, prev_t, cur_t, next_t):
    """Best fuzzy ratio of the anchor against windows over prev+cur+next cue
    text with more than half of the window inside the cited cue."""
    a = ntoks(anchor)
    P, C, N = ntoks(prev_t), ntoks(cur_t), ntoks(next_t)
    w = P + C + N
    c0, c1 = len(P), len(P) + len(C)
    best, seen_reasons = 0.0, set()
    for L in range(max(1, len(a) - 1), len(a) + 2):
        for i in range(0, max(1, len(w) - L + 1)):
            overlap = max(0, min(i + L, c1) - max(i, c0))
            if overlap * 2 <= L:
                continue
            core = w[i:i + L]
            if [x for x in core if protected(x)] != [x for x in a if protected(x)]:
                seen_reasons.add("protected")
                continue
            r = difflib.SequenceMatcher(None, a, core, autojunk=False).ratio()
            if r < FUZZY_MIN:
                continue
            if not noise_ok(a, core):
                seen_reasons.add("noise")
                continue
            if r > best:
                best = r
    if best:
        return best, None
    if "noise" in seen_reasons:
        return 0.0, "edits are not transcription noise (content word changed)"
    if "protected" in seen_reasons:
        return 0.0, "protected token mismatch (negation/number/unit/comparative/modal)"
    return 0.0, "no window overlaps the cited span"


def check_cite(sid, anchor, spans, order, allowed):
    """Returns (status, detail, matched source text or None)."""
    if "[[" in anchor or "]]" in anchor or "[[" in norm(anchor) or "]]" in norm(anchor):
        return "fail", "anchor contains citation syntax", None
    s = spans.get(sid)
    if s is None:
        return "fail", "unknown span id", None
    if allowed is not None and sid not in allowed:
        return "fail", "span outside unit", None
    at, st = tokens(anchor), tokens(s["text"])
    words = [t for t in at if re.match(r"\w", t)]
    if len(words) > MAX_WORDS:
        return "fail", f"anchor too long ({len(words)} words)", None
    span_words = [t for t in st if re.match(r"\w", t)]
    short_span = len(span_words) < MIN_WORDS and len(norm(s["text"])) < MIN_CHARS
    if short_span:
        # decision 1 exception: a short span is quoted whole, stopwords or not
        if words != span_words:
            return "fail", "short span: anchor must equal the whole span", None
        return "ok", "exact", display_safe(s["text"])
    if all(w in STOPWORDS for w in words):
        return "fail", "anchor is only stopwords", None
    if len(words) < MIN_WORDS and len(norm(anchor)) < MIN_CHARS:
        return "fail", f"anchor too short ({len(words)} words, {len(norm(anchor))} chars)", None
    hit = find_tokens(anchor, s["text"])
    if hit is not None:
        return "ok", "exact", display_safe(hit)
    if s.get("kind") in NOISY_KINDS:
        i = order.index(sid)
        prev_t = spans[order[i - 1]]["text"] if i > 0 else ""
        next_t = spans[order[i + 1]]["text"] if i + 1 < len(order) else ""
        r, why = fuzzy(anchor, prev_t, s["text"], next_t)
        if r >= FUZZY_MIN:
            return "ok", f"fuzzy {r:.2f}", display_safe(s["text"])
        return "fail", f"anchor not in span ({why or f'fuzzy {r:.2f}'})", None
    return "fail", "anchor not in span", None


def verify(store, brief_path, allow_files, where=None, text=None):
    spans, order = load_spans(store)
    allowed = None
    if allow_files:
        allowed = set()
        for f in allow_files:
            allowed |= {l.strip() for l in open(f) if l.strip()}
    if text is None:
        text = open(brief_path, encoding="utf-8").read()
    cites, failures, items = [], [], []
    section, seen, where_lines = None, [], []
    for ln_no, line in enumerate(text.split("\n"), 1):
        if not line.strip():
            continue
        h = re.match(r"^\s*#", line)
        if h:
            m = re.fullmatch(r"## (.+)", line.rstrip())
            name = m.group(1) if m else None
            if name not in SCHEMA:
                failures.append({"line": ln_no, "reason": f"heading not in schema: {line.strip()[:60]}"})
                section = "?"
                continue
            if name in seen or (seen and SCHEMA.index(name) < SCHEMA.index(seen[-1])):
                failures.append({"line": ln_no, "reason": f"heading out of order or repeated: {name}"})
            seen.append(name)
            section = name
            continue
        if section is None:
            failures.append({"line": ln_no, "reason": "text before the first heading"})
            continue
        if section == "?":
            failures.append({"line": ln_no, "reason": "text under a non-schema heading"})
            continue
        if section == "Where":
            where_lines.append(line.strip())
            if CITE.search(line) or BARE_CITE.search(line):
                failures.append({"line": ln_no, "reason": "cite in Where"})
            if len(where_lines) > 1:
                failures.append({"line": ln_no, "reason": "Where holds one generated line only"})
            continue
        item_re = r"^(\d+)\. \S" if section == "Quiz seeds" else r"^- \S"
        if not re.match(item_re, line):
            failures.append({"line": ln_no, "reason": f"not a schema item in {section}"})
        if section == "Prerequisites":
            if not PREREQ_ITEM.match(line):
                failures.append({"line": ln_no, "reason": "Prerequisites items must start 'Assumes:' or 'Earlier unit:'"})
            if CITE.search(line):
                failures.append({"line": ln_no, "reason": "cite in Prerequisites (outside knowledge only)"})
        found = CITE.findall(line)
        if len(BARE_CITE.findall(line)) > len(found):
            failures.append({"line": ln_no, "reason": "malformed cite"})
        item = {"line": ln_no, "section": section, "ok": 0, "bad": 0}
        for sid, anchor in found:
            st, why, src = check_cite(sid, anchor, spans, order, allowed)
            cites.append({"line": ln_no, "id": sid, "anchor": anchor, "status": st, "detail": why,
                          "match": ("fuzzy" if why.startswith("fuzzy") else "exact") if st == "ok" else None,
                          "source_text": src, "locator": spans[sid]["locator"] if sid in spans else None})
            if st == "ok":
                item["ok"] += 1
            else:
                item["bad"] += 1
                failures.append({"line": ln_no, "id": sid, "reason": why})
        items.append(item)
        if section in CLAIM_SECTIONS and not found:
            failures.append({"line": ln_no, "reason": "claim without cite"})
        m = SELF_LOCATOR.search(CITE.sub("", line))
        if m:
            failures.append({"line": ln_no, "reason": "self-written locator", "text": m.group(0)})
    for r in REQUIRED - set(seen):
        failures.append({"line": 0, "reason": f"missing section: {r}"})
    if where is not None and where_lines != [where.strip()]:
        failures.append({"line": 0, "reason": "Where differs from the code-generated value"})
    if not cites:
        failures.append({"line": 0, "reason": "brief has no cites"})
    return {"brief": brief_path, "cites": len(cites), "ok": sum(c["status"] == "ok" for c in cites),
            "fuzzy": sum(c["match"] == "fuzzy" for c in cites), "failures": failures, "detail": cites,
            "items": items, "pass": not failures}


def section_of(outline, pdf_index):
    """Title of the deepest outline item starting at or before a PDF page (1-based)."""
    best = None
    for o in outline:
        if o.get("pdf_index") is not None and o["pdf_index"] <= pdf_index:
            if best is None or o["pdf_index"] >= best["pdf_index"]:
                best = o
    return best["title"] if best else None


def locator_text(store, span, _cache={}):
    """Human locator for a span. PDF labels that occur on several pages (a
    roman-numbered index after roman front matter) carry their section."""
    if store not in _cache:
        lj = os.path.join(store, "labels.json")
        oj = os.path.join(store, "outline.json")
        _cache[store] = (json.load(open(lj)) if os.path.exists(lj) else {},
                         json.load(open(oj)) if os.path.exists(oj) else [])
    labels, outline = _cache[store]
    loc = display_safe(span["locator"])
    if not re.fullmatch(r"p\d{4}", span["segment"]):
        return loc
    text = loc if loc.startswith("PDF p.") else f"p. {loc}"
    if len(labels.get("label_to_pdf", {}).get(span["locator"], [])) > 1:
        idx = int(span["segment"][1:])
        sec = section_of(outline, idx)
        text += f" ({sec})" if sec else f" (PDF p. {idx})"
    return text


def render(store, brief_path):
    """Citations render from the SOURCE span text (the matched substring),
    never from the model's anchor; bidi and control characters are removed."""
    spans, order = load_spans(store)

    def sub(m):
        st, why, src = check_cite(m.group(1), m.group(2), spans, order, None)
        if st != "ok":
            return "(citation removed)"
        mark = " [fuzzy]" if why.startswith("fuzzy") else ""
        return f"({locator_text(store, spans[m.group(1)])}{mark}: “{src}”)"
    return display_safe(CITE.sub(sub, open(brief_path, encoding="utf-8").read()))


def main():
    a = sys.argv[1:]
    if len(a) < 2:
        sys.exit(__doc__)
    store, brief = a[0], a[1]
    if "--render" in a:
        print(render(store, brief))
        return
    allow = [a[i + 1] for i, x in enumerate(a) if x == "--allow"]
    where = a[a.index("--where") + 1] if "--where" in a else None
    rep = verify(store, brief, allow, where)
    if "--json" in a:
        json.dump(rep, open(a[a.index("--json") + 1], "w"), indent=1, ensure_ascii=False)
    print(f"{'PASS' if rep['pass'] else 'FAIL'} cites={rep['cites']} ok={rep['ok']} fuzzy={rep['fuzzy']} failures={len(rep['failures'])}")
    for f in rep["failures"]:
        print("  line", f.get("line"), f.get("id", ""), "-", f["reason"], f.get("text", ""))
    sys.exit(0 if rep["pass"] else 1)


if __name__ == "__main__":
    main()
